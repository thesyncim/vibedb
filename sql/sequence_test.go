func TestParseSequenceDDL(t *testing.T) {
	t.Run("create defaults", func(t *testing.T) {
		stmt, err := ParseStatement(`CREATE SEQUENCE order_seq`)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		if stmt.Kind != KindCreateSequence || stmt.CreateSequence == nil {
			t.Fatalf("got kind=%v, want KindCreateSequence", stmt.Kind)
		}
		cs := stmt.CreateSequence
		if cs.Name != "order_seq" || cs.IfNotExists {
			t.Fatalf("unexpected CreateSequence: %+v", cs)
		}
		if KindOf(`CREATE SEQUENCE order_seq`) != KindCreateSequence {
			t.Fatalf("KindOf CREATE SEQUENCE mismatch")
		}
	})

	t.Run("create all options ascending", func(t *testing.T) {
		src := `CREATE SEQUENCE IF NOT EXISTS s1 AS BIGINT INCREMENT BY 5 MINVALUE 10 MAXVALUE 9223372036854775807 START WITH 10 CACHE 64 CYCLE`
		stmt, err := ParseStatement(src)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		cs := stmt.CreateSequence
		if !cs.IfNotExists || cs.Name != "s1" {
			t.Fatalf("unexpected header: %+v", cs)
		}
		o := cs.Options
		if !o.HasDataType || o.DataType != "BIGINT" ||
			!o.HasIncrement || o.Increment != 5 ||
			!o.HasMinValue || o.MinValue != 10 ||
			!o.HasMaxValue || o.MaxValue != math.MaxInt64 ||
			!o.HasStart || o.Start != 10 ||
			!o.HasCache || o.Cache != 64 ||
			!o.HasCycle || !o.Cycle {
			t.Fatalf("unexpected options: %+v", o)
		}
	})

	t.Run("create descending min int64", func(t *testing.T) {
		src := `CREATE SEQUENCE s_desc INCREMENT -1 MINVALUE -9223372036854775808 MAXVALUE -1 START -1 NO CYCLE`
		stmt, err := ParseStatement(src)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		o := stmt.CreateSequence.Options
		if o.Increment != -1 || o.MinValue != math.MinInt64 || o.MaxValue != -1 || o.Start != -1 || !o.HasCycle || o.Cycle {
			t.Fatalf("unexpected descending options: %+v", o)
		}
	})

	t.Run("alter sequence", func(t *testing.T) {
		src := `ALTER SEQUENCE IF EXISTS s1 INCREMENT 2 NO MINVALUE NO MAXVALUE RESTART WITH 100 CACHE 16 NO CYCLE`
		stmt, err := ParseStatement(src)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		if stmt.Kind != KindAlterSequence || stmt.AlterSequence == nil {
			t.Fatalf("got kind=%v", stmt.Kind)
		}
		if KindOf(src) != KindAlterSequence {
			t.Fatalf("KindOf ALTER SEQUENCE mismatch")
		}
		as := stmt.AlterSequence
		if !as.IfExists || as.Name != "s1" || !as.Options.NoMinValue || !as.Options.NoMaxValue ||
			!as.Options.HasRestart || !as.Options.HasRestartValue || as.Options.RestartValue != 100 ||
			as.Options.Increment != 2 || as.Options.Cache != 16 || as.Options.Cycle {
			t.Fatalf("unexpected AlterSequence: %+v", as)
		}
	})

	t.Run("alter sequence bare restart", func(t *testing.T) {
		stmt, err := ParseStatement(`ALTER SEQUENCE s1 RESTART CACHE 4`)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		o := stmt.AlterSequence.Options
		if !o.HasRestart || o.HasRestartValue || !o.HasCache || o.Cache != 4 {
			t.Fatalf("unexpected bare restart options: %+v", o)
		}
	})

	t.Run("drop sequence", func(t *testing.T) {
		stmt, err := ParseStatement(`DROP SEQUENCE IF EXISTS s1 RESTRICT`)
		if err != nil {
			t.Fatalf("ParseStatement: %v", err)
		}
		if stmt.Kind != KindDropSequence || stmt.DropSequence == nil {
			t.Fatalf("got kind=%v", stmt.Kind)
		}
		if KindOf(`DROP SEQUENCE s1`) != KindDropSequence {
			t.Fatalf("KindOf DROP SEQUENCE mismatch")
		}
		if !stmt.DropSequence.IfExists || !stmt.DropSequence.Restrict || stmt.DropSequence.Name != "s1" {
			t.Fatalf("unexpected DropSequence: %+v", stmt.DropSequence)
		}
	})
}

func TestParseSerialIdentityAndOverriding(t *testing.T) {
	ddl := `CREATE TABLE items (
		id BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 10) PRIMARY KEY,
		seq_id BIGSERIAL,
		small_id SMALLSERIAL NOT NULL,
		int_id SERIAL,
		opt_id INTEGER GENERATED BY DEFAULT AS IDENTITY (MINVALUE 1 MAXVALUE 1000 CYCLE)
	)`
	stmt, err := ParseStatement(ddl)
	if err != nil {
		t.Fatalf("ParseStatement DDL: %v", err)
	}
	cols := stmt.CreateTable.Columns
	if len(cols) != 5 {
		t.Fatalf("len(cols) = %d, want 5", len(cols))
	}
	if cols[0].Identity != IdentityAlways || cols[0].IdentityOptions == nil ||
		cols[0].IdentityOptions.Start != 100 || cols[0].IdentityOptions.Increment != 10 || !cols[0].Required {
		t.Fatalf("col[0] unexpected: %+v", cols[0])
	}
	if cols[1].Serial != SerialBig || !cols[1].Required || cols[1].Type&TypeNull != 0 {
		t.Fatalf("col[1] unexpected: %+v", cols[1])
	}
	if cols[2].Serial != SerialSmall || !cols[2].Required {
		t.Fatalf("col[2] unexpected: %+v", cols[2])
	}
	if cols[3].Serial != SerialInt || !cols[3].Required {
		t.Fatalf("col[3] unexpected: %+v", cols[3])
	}
	if cols[4].Identity != IdentityByDefault || cols[4].IdentityOptions == nil || !cols[4].IdentityOptions.Cycle {
		t.Fatalf("col[4] unexpected: %+v", cols[4])
	}

	insSys, err := ParseStatement(`INSERT INTO items (id, opt_id) OVERRIDING SYSTEM VALUE VALUES (42, DEFAULT)`)
	if err != nil {
		t.Fatalf("ParseStatement OVERRIDING SYSTEM VALUE: %v", err)
	}
	if insSys.Insert.Overriding != InsertOverridingSystemValue {
		t.Fatalf("Overriding = %v, want InsertOverridingSystemValue", insSys.Insert.Overriding)
	}
	if insSys.Insert.Rows[0].Values[1].Kind != OperandDefault {
		t.Fatalf("Values[1].Kind = %v, want OperandDefault", insSys.Insert.Rows[0].Values[1].Kind)
	}

	insUser, err := ParseStatement(`INSERT INTO items (id) OVERRIDING USER VALUE VALUES (99)`)
	if err != nil {
		t.Fatalf("ParseStatement OVERRIDING USER VALUE: %v", err)
	}
	if insUser.Insert.Overriding != InsertOverridingUserValue {
		t.Fatalf("Overriding = %v, want InsertOverridingUserValue", insUser.Insert.Overriding)
	}

	// Sequence functions parse cleanly.
	sel, err := ParseStatement(`SELECT nextval('s'), currval('s'), setval('s', 10), setval('s', 20, false), lastval()`)
	if err != nil {
		t.Fatalf("ParseStatement sequence funcs: %v", err)
	}
	if len(sel.Select.Columns) != 5 {
		t.Fatalf("len(Columns) = %d, want 5", len(sel.Select.Columns))
	}

	// Reject invalid combinations.
	for _, bad := range []string{
		`CREATE TABLE bad1 (id SERIAL NULL)`,
		`CREATE TABLE bad2 (id TEXT GENERATED ALWAYS AS IDENTITY)`,
		`CREATE TABLE bad3 (id INT DEFAULT 1 GENERATED ALWAYS AS IDENTITY)`,
		`CREATE TABLE bad4 (id INT GENERATED ALWAYS AS IDENTITY NULL)`,
		`CREATE SEQUENCE bad5 INCREMENT 1 INCREMENT 2`,
		`CREATE SEQUENCE bad6 MINVALUE 1 NO MINVALUE`,
		`CREATE SEQUENCE bad7 RESTART 1`,
		`CREATE TABLE bad8 (id SERIAL DEFAULT 5)`,
	} {
		if _, err := ParseStatement(bad); err == nil {
			t.Fatalf("expected parse error for %q", bad)
		}
	}
}
